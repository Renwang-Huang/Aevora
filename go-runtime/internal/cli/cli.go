func Command(factory host.Factory) *cobra.Command {
	var profilePath, run, root string
	var proposals bool
	var consolePort int
	c := &cobra.Command{Use: "aevora", SilenceErrors: true, SilenceUsage: true}
	c.PersistentFlags().StringVar(&profilePath, "config", "", "Protected Host profile")
	var versionJSON bool
	version := &cobra.Command{Use: "version", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		if versionJSON {
			return json.NewEncoder(cmd.OutOrStdout()).Encode(buildinfo.Current())
		}
		_, e := fmt.Fprintf(cmd.OutOrStdout(), "aevora %s (%s)\n", buildinfo.Version, buildinfo.Revision)
		return e
	}}
	version.Flags().BoolVar(&versionJSON, "json", false, "Print actual native build and dependency metadata")
	c.AddCommand(version)
	serve := &cobra.Command{Use: "serve", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		p, e := host.Load(profilePath)
		if e != nil {
			return e
		}
		ctx, stop := signal.NotifyContext(cmd.Context(), os.Interrupt, syscall.SIGTERM)
		defer stop()
		ctx, cancel := context.WithCancel(ctx)
		defer cancel()
		h, e := host.New(ctx, p, run, proposals, factory)
		if e != nil {
			return e
		}
		defer h.Close()
		output := map[string]any{"status": "READY", "run_id": h.RunID(), "events": h.Folder() + "/mcp_events.jsonl", "engine": "python", "console": "Use the existing read-only Console"}
		var viewer *observatory.Server
		if p.Database.Kind == "sqlite" {
			selected, ok := h.Backend().(*native.Runtime)
			if !ok {
				return engine.ErrUnavailable
			}
			port := p.Console.Port
			if cmd.Flags().Changed("port") {
				port = consolePort
			}
			viewer, e = observatory.Listen(ctx, port, &observatory.Reader{Store: selected.Storage(), Runtime: observatory.RuntimeHeaders(h.SessionDirectories), HostState: func() map[string]any {
				raw, _ := json.Marshal(h.Snapshot())
				v := map[string]any{}
				json.Unmarshal(raw, &v)
				return v
			}})
			if e != nil {
				return e
			}
			go func() { viewer.Wait(); cancel() }()
			output["engine"] = "go-sqlite"
			output["console"] = viewer.URL
		}
		if e = h.Ready(fmt.Sprint(output["console"])); e != nil {
			return e
		}
		if e = json.NewEncoder(cmd.OutOrStdout()).Encode(output); e == nil {
			e = h.Serve(ctx)
		}
		if viewer != nil {
			if closeErr := viewer.Close(); e == nil {
				e = closeErr
			}
		}
		if closeErr := h.Close(); e == nil {
			e = closeErr
		}
		return e
	}}
	serve.Flags().StringVar(&run, "run-id", "", "Trusted Run identity (generated by default)")
	serve.Flags().BoolVar(&proposals, "enable-proposals", false, "Enable untrusted proposals")
	serve.Flags().IntVar(&consolePort, "port", 17805, "Override the profile Console port without stopping any existing service")
	c.AddCommand(serve)
	var demoPort int
	demo := &cobra.Command{Use: "demo", Short: "Open the embedded, independently pinned public replay", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		ctx, cancel := signal.NotifyContext(cmd.Context(), os.Interrupt, syscall.SIGTERM)
		defer cancel()
		viewer, e := observatory.Listen(ctx, demoPort, nil)
		if e != nil {
			return e
		}
		if e = json.NewEncoder(cmd.OutOrStdout()).Encode(map[string]any{"status": "LISTENING", "url": viewer.URL + "/?mode=REPLAY", "mode": "REPLAY", "contract_sha256": observatory.ReplayPin}); e != nil {
			viewer.Close()
			return e
		}
		select {
		case <-ctx.Done():
		case <-viewer.Done():
		}
		return viewer.Close()
	}}
	demo.Flags().IntVar(&demoPort, "port", 17804, "Loopback replay Console port")
	c.AddCommand(demo)
	c.AddCommand(&cobra.Command{Use: "doctor", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		p, e := host.Load(profilePath)
		if e != nil {
			return e
		}
		if p.Database.Kind == "sqlite" {
			response, e := trustedCall(cmd.Context(), p, "", "diagnostics", map[string]any{})
			if e != nil {
				return e
			}
			if response["status"] == "COMPLETED" {
				if e = doctor(cmd.Context(), p, response); e != nil {
					return e
				}
			}
			return emitOperation(cmd, response)
		}
		configured := filepath.IsAbs(os.Getenv("AEVORA_HOST_PYTHON"))
		return json.NewEncoder(cmd.OutOrStdout()).Encode(map[string]any{"status": "HOST_CONFIG_VALID", "python_engine_configured": configured, "database": "NOT_PROBED", "mcp": "NOT_PROBED", "runtime_ready": "NOT_PROVEN"})
	}})
	var directory, operation string
	var connectorGrant string
	var automaticSession, routeWorkspace bool
	status := &cobra.Command{Use: "operation-status", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		v, e := host.OperationStatus(directory, operation)
		if e != nil {
			return e
		}
		return json.NewEncoder(cmd.OutOrStdout()).Encode(v)
	}}
	status.Flags().StringVar(&directory, "session-directory", "", "Protected immutable session directory")
	status.Flags().StringVar(&operation, "operation-id", "", "Operation identity returned by the Host")
	c.AddCommand(status)
	bridge := &cobra.Command{Use: "mcp-connect", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		if connectorGrant != "" {
			if root != "" || run != "" || automaticSession || routeWorkspace {
				return engine.ErrInvalid
			}
			return host.PersistentBridge(cmd.Context(), "", "", connectorGrant, false, cmd.InOrStdin(), cmd.OutOrStdout())
		}
		if root == "" {
			return errors.New("SESSION_ROOT_REQUIRED")
		}
		if automaticSession && run != "" {
			return engine.ErrInvalid
		}
		if routeWorkspace {
			if !automaticSession {
				return engine.ErrInvalid
			}
			return host.PersistentWorkspaceBridge(cmd.Context(), root, cmd.InOrStdin(), cmd.OutOrStdout())
		}
		return host.PersistentBridge(cmd.Context(), root, run, "", automaticSession, cmd.InOrStdin(), cmd.OutOrStdout())
	}}
	bridge.Flags().StringVar(&root, "session-root", "", "Protected stable session root (no Host profile required)")
	bridge.Flags().StringVar(&run, "run-id", "", "Authorized Run selector; omitted selects the Host's initial Run")
	bridge.Flags().StringVar(&connectorGrant, "grant", "", "Explicit protected Run connector capability for namespaced clients")
	bridge.Flags().BoolVar(&automaticSession, "auto-session", false, "Request a fresh Host-measured scoped task; no Host profile is read")
	bridge.Flags().BoolVar(&routeWorkspace, "route-workspace", false, "Select a registered project from connector cwd; Host authorization still applies")
	c.AddCommand(bridge)
	config := &cobra.Command{Use: "mcp-config", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, _ []string) error {
		p, e := host.Load(profilePath)
		if e != nil {
			return e
		}
		exe, e := os.Executable()
		if e != nil {
			return e
		}
		if run != "" {
			response, e := host.ManagementCall(cmd.Context(), p, run, "open-run", map[string]any{"public_context": json.RawMessage(p.Session.Facts), "enable_proposals": proposals})
			if e != nil {
				return e
			}
			if response["status"] != "COMPLETED" {
				return &operationError{fmt.Sprint(response["status"]), fmt.Sprint(response["operation_id"]), fmt.Sprint(response["code"])}
			}
			_, e = fmt.Fprintf(cmd.OutOrStdout(), "[mcp_servers.aevora]\ncommand = %s\nargs = [\"mcp-connect\", \"--session-root\", %s, \"--run-id\", %s]\n", strconv.Quote(exe), strconv.Quote(p.Session.Root), strconv.Quote(run))
			return e
		}
		_, e = fmt.Fprintf(cmd.OutOrStdout(), "[mcp_servers.aevora]\ncommand = %s\nargs = [\"mcp-connect\", \"--session-root\", %s]\n", strconv.Quote(exe), strconv.Quote(p.Session.Root))
		return e
	}}
	config.Flags().StringVar(&run, "run-id", "", "Authorize a named Run on the active Host using the protected profile facts")
	config.Flags().BoolVar(&proposals, "enable-proposals", false, "Enable untrusted proposals for a named Run")
	c.AddCommand(config)
	addNativeCommands(c, &profilePath)
	addTransferCommands(c, &profilePath)
	var project string
	addWorkflow(c, &profilePath, &project)
	return c
}

func Execute(ctx context.Context, args []string, input io.Reader, output, stderr io.Writer, f host.Factory) int {
	c := Command(f)
	c.SetArgs(args)
	c.SetIn(input)
	c.SetOut(output)
	c.SetErr(stderr)
	if e := c.ExecuteContext(ctx); e != nil {
		var check *checkExit
		if errors.As(e, &check) {
			return check.code
		}
		next := "Check the protected profile, owned backend and runtime documentation; preserve existing session evidence."
		if errors.Is(e, engine.ErrRunContext) {
			next = "Restore the Run's original trusted facts or choose a new --run-id; preserve its sessions and context pin."
		}
		message := map[string]any{"status": "ERROR", "code": publicError(e), "next_step": next}
		var migration *clientconfig.MigrationFailure
		if errors.As(e, &migration) {
			message["recovery_receipt"] = migration.Journal
			message["next_step"] = "Preserve external edits and inspect the migration journal. Retry the exact migrate command to reconcile owned blocks, or preview --undo. No credentials or Run grants were transferred."
		}
		var upgradeErr *upgradeFailure
		if errors.As(e, &upgradeErr) {
			message["upgrade_status"], message["receipt"] = upgradeErr.state, upgradeErr.receipt
			message["next_step"] = "Inspect the local upgrade receipt. Business operations were not replayed and the database was not overwritten."
		}
		var operation *operationError
		if errors.As(e, &operation) {
			message["status"], message["operation_id"] = operation.status, operation.id
		}
		if workflowCommand(c, args) {
			code := publicError(e)
			message["next_step"] = advice(code)
			cmd, _, _ := c.Find(args)
			machine, _ := cmd.Flags().GetBool("json")
			if !machine {
				fmt.Fprintf(stderr, "Aevora: %s\nNext: %s\n", code, advice(code))
				if migration != nil {
					fmt.Fprintf(stderr, "Recovery journal: %s\n", migration.Journal)
				}
				if operation != nil {
					fmt.Fprintf(stderr, "Operation: %s (%s)\n", operation.id, operation.status)
				}
				return 2
			}
		}
		json.NewEncoder(stderr).Encode(message)
		return 2
	}
	return 0
}

func publicError(e error) string {
	if e.Error() == "AEVORA_CLIENT_MIGRATION_INCOMPLETE" {
		return e.Error()
	}
	if e.Error() == "AEVORA_UPGRADE_CAPTURE_RECORD_READER_REQUIRED" {
		return e.Error()
	}
	if e.Error() == "AEVORA_CAPTURE_INVALID" || e.Error() == "AEVORA_CAPTURE_OUTBOX_FULL" || e.Error() == "AEVORA_CAPTURE_RECOVERY_CONFLICT" {
		return e.Error()
	}
	var upgraded *upgradeFailure
	if errors.As(e, &upgraded) {
		return upgraded.Error()
	}
	upgradeCode, _, _ := strings.Cut(e.Error(), ";")
	switch upgradeCode {
	case "AEVORA_UPGRADE_INVALID_BINARY_OR_CHECKSUM", "AEVORA_UPGRADE_TARGET_CHANGED", "AEVORA_UPGRADE_PLATFORM_NOT_VALIDATED", "AEVORA_UPGRADE_REQUIRES_PROJECT_AND_ABSOLUTE_BINARY", "AEVORA_UPGRADE_PLATFORM_OR_SCHEMA_MISMATCH", "AEVORA_UPGRADE_TARGET_IS_NOT_OWNED_SERVICE_EXECUTABLE", "AEVORA_UPGRADE_RESUME_REQUIRES_RUNNING_HOST", "AEVORA_UPGRADE_OTHER_HOSTS_ACTIVE", "AEVORA_UPGRADE_HOST_NOT_READY", "AEVORA_UPGRADE_BACKUP_FAILED", "AEVORA_UPGRADE_INVALID_BACKUP_RECEIPT", "AEVORA_UPGRADE_READINESS_FAILED":
		return upgradeCode
	}

	if e.Error() == engine.ErrResultLimit.Error() {
		return engine.ErrResultLimit.Error()
	}
	if e.Error() == "CONSOLE_BIND_FAILED" {
		return "CONSOLE_BIND_FAILED"
	}
	if e.Error() == "AEVORA_TARGET_MUST_BE_NEW" {
		return "AEVORA_TARGET_MUST_BE_NEW"
	}
	if errors.Is(e, engine.ErrRunContext) || e.Error() == engine.ErrRunContext.Error() {
		return engine.ErrRunContext.Error()
	}
	v := e.Error()
	if v == "AEVORA_PROJECT_BACKEND_UNAVAILABLE" {
		return v
	}
	for _, code := range []string{"AEVORA_PROJECT_AMBIGUOUS", "AEVORA_CONTEXT_OBSERVATION_INVALID", "AEVORA_LOCAL_BINDING_INVALID", "AEVORA_PROJECT_NOT_REGISTERED", "AEVORA_PROJECT_BACKEND_CHANGED", "AEVORA_PROJECT_CONFIG_CONFLICT", "AEVORA_AUDIT_LIMIT", "AEVORA_REGISTER_EXISTING_PROFILE", "AEVORA_TASK_NOT_FOUND", "AEVORA_CLIENT_UNSUPPORTED", "AEVORA_CLIENT_CONFIG_CONFLICT", "AEVORA_CLIENT_CONFIG_CHECK_FAILED", "AEVORA_CLIENT_EXECUTABLE_REQUIRED", "AEVORA_CLIENT_BINDING_OVERRIDE_DENIED", "AEVORA_CLIENT_EXITED_UNSUCCESSFULLY", "AEVORA_TASK_CLOSE_UNKNOWN", "AEVORA_USER_SERVICE_UNAVAILABLE", "AEVORA_SERVICE_CONFIGURATION_CONFLICT", "AEVORA_HOST_READINESS_TIMEOUT", "AEVORA_RUNTIME_STATUS_STALE", "AEVORA_STATUS_WRITE_FAILED", "AEVORA_GRANT_UNAVAILABLE", "AEVORA_CAPTURE_HOOK_CONFLICT", "AEVORA_CAPTURE_HOOK_RECEIPT_FAILED", "AEVORA_ROUTE_IN_USE", "AEVORA_ROUTE_NOT_REMOVABLE"} {
		if v == code {
			return code
		}
	}
	for _, code := range []string{"HOST_CONFIG_REQUIRED", "HOST_CONFIG_INVALID", "SESSION_ROOT_REQUIRED", "SESSION_NOT_STARTED", "SESSION_PATH_TOO_LONG", "AEVORA_BACKEND_ALREADY_OWNED", "AEVORA_BACKEND_ROOT_CONFLICT", "AEVORA_PLATFORM_NOT_SUPPORTED", "AEVORA_GRAPH_UNAVAILABLE", "AEVORA_WORKER_CONFIGURATION_REQUIRED", "AEVORA_LEGACY_PLATFORM_UNSUPPORTED", "AEVORA_OPERATION_NOT_FOUND", "AEVORA_INVALID_RECORD", "AEVORA_IMMUTABLE_CONFLICT", "AEVORA_STORAGE_INCOMPATIBLE", "AEVORA_UNSAFE_HOST_STATE", "AEVORA_HOST_UNAVAILABLE", "AEVORA_INVALID_OR_UNAUTHORIZED_INPUT", "AEVORA_OPERATION_UNKNOWN", "AEVORA_GRAPH_RECORD_ERROR", "AEVORA_NATIVE_CONFIG_REQUIRED", "AEVORA_PROJECT_ALREADY_EXISTS", "AEVORA_RUN_NOT_AUTHORIZED", "AEVORA_RUN_LIMIT"} {
		if v == code {
			return v
		}
	}
	return "AEVORA_RUNTIME_ERROR"
}
