"""Command and synthetic Responses fixture contracts; no live model requests.

Actual installed CLI retry evidence is generated by phase35_codex_retry_probe.
These tests do not claim that a simulated HTTP response is a real model task.
"""
import json
from pathlib import Path

import pytest

from benchmark.resources import PARTICIPANT_LIMITS
from integrations.codex_agent import CodexConfig, native_command
from scripts.phase35_codex_retry_probe import MODEL, TEXT, successful_events


def overrides(command):
    return {value.split("=", 1)[0]: json.loads(value.split("=", 1)[1])
            for index, value in enumerate(command) if index and command[index - 1] == "-c"}


def test_gateway_has_two_finite_native_http_and_stream_retries():
    config = CodexConfig(Path("/synthetic/codex"), Path("/synthetic/unused-secret"),
                         model=MODEL, provider_id="gateway", reasoning_effort="max")
    command = native_command(config, "http://127.0.0.1:9180/v1")
    values = overrides(command)
    assert values["model_providers.orderflow_broker.request_max_retries"] == 2
    assert values["model_providers.orderflow_broker.stream_max_retries"] == 2
    assert values["model_providers.orderflow_broker.stream_idle_timeout_ms"] == 120000
    assert values["model_reasoning_effort"] == "max"
    index = command.index("unbounded_connection_retries")
    assert command[index - 1] == "--disable"
    assert config.timeout_seconds == 900 and config.request_budget == 160
    assert config.max_request_concurrency == 4
    assert PARTICIPANT_LIMITS.memory_bytes == 2 * 1024 ** 3


def test_legacy_retains_zero_native_retries_and_ephemeral_contract():
    command = native_command(CodexConfig(Path("/synthetic/codex"), Path("/synthetic/unused-secret")),
                             "http://127.0.0.1:1/v1")
    values = overrides(command)
    assert values["model_providers.orderflow_broker.request_max_retries"] == 0
    assert values["model_providers.orderflow_broker.stream_max_retries"] == 0
    assert "--ephemeral" in command


@pytest.mark.parametrize("attempt", (1, 2, 3))
def test_synthetic_recovery_fixture_has_complete_responses_terminal(attempt):
    events = [json.loads(frame.removeprefix(b"data: ")) for frame in successful_events(attempt).split(b"\n\n") if frame]
    assert [event["type"] for event in events] == ["response.created", "response.output_item.done", "response.completed"]
    response = events[-1]["response"]
    assert response["status"] == "completed" and response["model"] == MODEL
    assert response["reasoning"]["effort"] == "max"
    assert response["output"][0]["content"][0]["text"] == TEXT
