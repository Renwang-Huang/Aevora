import { build } from 'esbuild';
import { mkdir, copyFile, readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const target='src/aevora_observatory/static';
await mkdir(`${target}/assets`,{recursive:true});
await build({entryPoints:['web/app.js'],bundle:true,minify:true,target:'es2022',legalComments:'eof',outfile:`${target}/assets/app.js`,sourcemap:false});
await copyFile('web/index.html',`${target}/index.html`);
await build({entryPoints:['web/journey.js'],bundle:true,minify:true,target:'es2022',legalComments:'eof',outfile:`${target}/assets/journey.js`,sourcemap:false});
await copyFile('web/journey.html',`${target}/journey.html`);
await copyFile('web/gen2_history.json',`${target}/gen2_history.json`);
const files={};
for(const p of ['index.html','journey.html','gen2_history.json',...(await readdir(`${target}/assets`)).sort().map(n=>`assets/${n}`)])files[p]=createHash('sha256').update(await readFile(`${target}/${p}`)).digest('hex');
await writeFile(`${target}/BUILD_MANIFEST.json`,JSON.stringify({product:'Aevora',kind:'PUBLIC_STATIC_BUILD',node:process.version,files},null,2)+'\n');
console.log(JSON.stringify({status:'BUILT',files:Object.keys(files).length,node:process.version}));
